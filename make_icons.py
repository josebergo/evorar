"""Regenerate evorar icon set from the SVG master.

The v0.2 icon was drawn pixel-by-pixel here; since v0.3 the master is
design/icon.svg ("E·压": letter E with a press-in arrow as its middle arm).
Run this script from code/ to rebuild every platform icon (ico/icns/png/…):

    python make_icons.py

Requires the Tauri CLI (npx). design-mac.md's `icon.icns` step is covered —
the mac icon is generated by the same command.
"""
import subprocess, sys, pathlib

root = pathlib.Path(__file__).parent
src = root / "design" / "icon.svg"
out = root / "src-tauri" / "icons"

cmd = ["npx", "--yes", "@tauri-apps/cli", "icon", str(src), "-o", str(out)]
print(">", " ".join(cmd))
sys.exit(subprocess.call(cmd))

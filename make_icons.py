"""Regenerate evorar icon set from the transparent PNG master.

The master is design/icon.png: the selected orange archive and coral strap,
with the white backing removed using built-in ImageGen.
Run this script from code/ to rebuild every platform icon (ico/icns/png/…):

    python make_icons.py

Requires the Tauri CLI (npx). design-mac.md's `icon.icns` step is covered —
the mac icon is generated by the same command.
"""
import subprocess, sys, pathlib, shutil

root = pathlib.Path(__file__).parent
src = root / "design" / "icon.png"
out = root / "src-tauri" / "icons"

cmd = ["npx.cmd" if sys.platform == "win32" else "npx", "--no-install", "@tauri-apps/cli", "icon", str(src), "-o", str(out)]
print(">", " ".join(cmd))
subprocess.check_call(cmd)
subprocess.check_call([sys.executable, str(root / "make_icns.py")])
shutil.copyfile(out / "icon.ico", root / "src-tauri" / "bundle-manual" / "icon.ico")
